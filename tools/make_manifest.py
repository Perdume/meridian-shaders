def q(s: str) -> str:
    return '"' + s.replace('"', '\\"') + '"'


def num(v) -> str:
    return repr(float(v)) if isinstance(v, (int, float)) and not isinstance(v, bool) else str(v)


def coarse(default, extra):
    """Steps of 0.1 for options of 0.05 (11 values over 0..1), defaults on that grid from the minimum."""
    lo, hi, step = extra
    if step < 0.1:
        step = 0.1
    n = round((default - lo) / step)
    return round(lo + n * step, 4), (lo, hi, step)


def main() -> None:
    out = [HEADER]
    for mid, sprites in MATERIALS:
        out.append(f"[[materials]]\nid = {mid}\nsprites = [{', '.join(q(s) for s in sprites)}]\n")
    for color, blocks in LIGHTS:
        out.append(f"[[lights]]\ncolor = [{', '.join(num(c) for c in color)}]\nblocks = [{', '.join(q(b) for b in blocks)}]\n")
    ids = set()
    for oid, name, desc, kind, default, extra in OPTIONS:
        assert oid not in ids, oid
        ids.add(oid)
        o = [f"[[options]]", f"id = {q(oid)}", f"name = {q(name)}", f"description = {q(desc)}", f"type = {q(kind)}"]
        if kind == "bool":
            o.append(f"default = {'true' if default else 'false'}")
        elif kind == "choice":
            o.append(f"values = [{', '.join(q(v) for v in extra)}]")
            o.append(f"default = {q(default)}")
        else:
            default, (lo, hi, step) = coarse(default, extra)
            o += [f"default = {num(default)}", f"min = {num(lo)}", f"max = {num(hi)}", f"step = {num(step)}"]
        out.append("\n".join(o) + "\n")
    assert len(OPTIONS) <= 64, len(OPTIONS)
    listed = set()
    for pid, name, desc, items in PAGES:
        o = ["[[pages]]", f"id = {q(pid)}", f"name = {q(name)}"]
        if desc:
            o.append(f"description = {q(desc)}")
        if pid == "main":
            o.append("columns = 1")
        o.append(f"items = [{', '.join(q(i) for i in items)}]")
        out.append("\n".join(o) + "\n")
        listed.update(i for i in items if not i.startswith("page:"))
    missing = ids - listed
    assert not missing, f"options on no page: {missing}"
    out.append("[budget]\ngpu_ms = 4.0\n")
    (ROOT / "pack" / "horizon-shaders.toml").write_text("\n".join(out), encoding="utf-8")
    print(f"pack/horizon-shaders.toml: {len(OPTIONS)} options, {len(PAGES)} pages, "
          f"{len(MATERIALS)} materials, {len(LIGHTS)} lights")


if __name__ == "__main__":
    main()
